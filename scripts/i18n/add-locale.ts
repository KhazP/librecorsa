/**
 * Adds a language: a folder of empty area files under src/i18n/messages/<code>/ and its line in src/i18n/catalogs.ts.
 * An empty language shows in English until its messages are filled in (npm run i18n:missing / i18n:merge).
 *
 *   npm run i18n:add -- tr "Türkçe"
 *   npm run i18n:add -- ar "العربية" --rtl
 *
 * The code is a BCP 47 tag the browser reports (navigator.language): "tr", "pt-BR", "zh-Hant". The name is the
 * language's own name for itself.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { areas, CATALOGS_FILE, MESSAGES, writeJson } from "./catalog";

const args = process.argv.slice(2);
const [code, name] = args;
if (!code || !name || !/^[a-z]{2,3}(-[A-Za-z0-9]{2,4})?$/.test(code)) {
  console.error('Usage: npm run i18n:add -- <code> "<own name>" [--rtl]   e.g. tr "Türkçe"');
  process.exit(1);
}
const dir = join(MESSAGES, code);
if (existsSync(dir)) {
  console.error(`${code} is already there (${dir})`);
  process.exit(1);
}
mkdirSync(dir);
const list = areas();
for (const area of list) writeJson(join(dir, `${area}.json`), {});
const ident = (a: string) => a.replace(/[^A-Za-z0-9]/g, "_");
writeFileSync(
  join(dir, "index.ts"),
  [
    `// ${name}: generated by npm run i18n:add; each area file is translated from the English one beside it`,
    ...list.map((a) => `import ${ident(a)} from "./${a}.json";`),
    "",
    `const messages = { ${list.map((a) => (ident(a) === a ? a : `${JSON.stringify(a)}: ${ident(a)}`)).join(", ")} };`,
    "",
    "export default messages;",
    "",
  ].join("\n"),
);

const marker = "  // i18n:catalogs";
const catalogs = readFileSync(CATALOGS_FILE, "utf8");
if (!catalogs.includes(marker)) throw new Error(`No "${marker.trim()}" line in ${CATALOGS_FILE}`);
const rtl = args.includes("--rtl") ? ', dir: "rtl"' : "";
const line = `  ${JSON.stringify(code)}: { name: ${JSON.stringify(name)}${rtl}, load: () => import("./messages/${code}") },\n`;
writeFileSync(CATALOGS_FILE, catalogs.replace(marker, `${line}${marker}`));
console.log(`Added ${code} (${name}): ${dir} and its line in src/i18n/catalogs.ts. Next: npm run i18n:missing -- ${code} --out ${code}.json`);
