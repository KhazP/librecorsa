interface Decoder {
  memory: WebAssembly.Memory;
  __heap_base: WebAssembly.Global;
  decode_row: (blocks: number, rgba: number, count: number) => void;
}

let decoder: Decoder | null | undefined;

function getDecoder(): Decoder | null {
  if (decoder !== undefined) return decoder;
  try {
    const bytes = Uint8Array.from(atob(MODULE_BASE64), (char) => char.charCodeAt(0));
    const module = new WebAssembly.Module(bytes);
    decoder = new WebAssembly.Instance(module).exports as unknown as Decoder;
  } catch {
    // Without WASM support (or if disabled by CSP), let the caller try the embedded texture.
    decoder = null;
  }
  return decoder;
}

export function decodeBC7(
  data: Uint8Array, offset: number, width: number, height: number,
): Uint8Array | null {
  const wasm = getDecoder();
  if (!wasm) return null;
  const blocks = Math.ceil(width / 4);
  const blockRow = blocks * 16;
  const input = Number(wasm.__heap_base.value);
  const output = input + blockRow;
  const pages = Math.ceil((output + 4 * blockRow - wasm.memory.buffer.byteLength) / 65536);
  if (pages > 0) wasm.memory.grow(pages);

  const scratch = new Uint8Array(wasm.memory.buffer);
  const result = new Uint8Array(width * height * 4);
  for (let y = 0, from = offset; y < height; y += 4, from += blockRow) {
    scratch.set(data.subarray(from, from + blockRow), input);
    wasm.decode_row(input, output, blocks);
    for (let row = 0; row < 4 && y + row < height; row++) {
      const start = output + row * blockRow;
      result.set(scratch.subarray(start, start + width * 4), (y + row) * width * 4);
    }
  }
  return result;
}
